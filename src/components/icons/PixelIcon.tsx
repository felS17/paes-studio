export type PixelIconName = keyof typeof ICONS

/** Une los píxeles seguidos de cada fila: menos `<rect>` que uno por píxel. */
function toRects(rows: readonly string[]) {
  return rows.flatMap((row, y) =>
    [...row.matchAll(/#+/g)].map((run) => ({ x: run.index, y, width: run[0].length })),
  )
}

const RECTS = Object.fromEntries(
  Object.entries(ICONS).map(([name, rows]) => [name, toRects(rows)]),
) as Record<PixelIconName, ReturnType<typeof toRects>>

/** Ícono Pixel Art monocromo: hereda el color del texto (`currentColor`). Es solo visual: el nombre va en el texto o en `aria-label`. */
export function PixelIcon({ name, className }: { name: PixelIconName; className?: string }) {
  return (
    <svg
      viewBox="0 0 16 16"
      width="16"
      height="16"
      fill="currentColor"
      shapeRendering="crispEdges"
      aria-hidden
      className={cn('size-4 shrink-0', className)}
    >
      {RECTS[name].map(({ x, y, width }) => (
        <rect key={`${x}-${y}`} x={x} y={y} width={width} height="1" />
      ))}
    </svg>
  )
}
